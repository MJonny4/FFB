import { mapLegacyStrengthToTarget } from "@ffb/football";

export interface TeamSeedDefinition {
  legacyName: string;
  name: string;
  slug: string;
  abbreviation: string;
  shortName: string;
  city: string;
  stadiumName: string;
  foundedYear: number;
  primaryColor: string;
  secondaryColor: string;
  shirtTextColor: string;
  crestImageUrl: string;
  legacyStrength: number;
  targetStrength: number;
}

function team(definition: Omit<TeamSeedDefinition, "targetStrength">): TeamSeedDefinition {
  return {
    ...definition,
    targetStrength: mapLegacyStrengthToTarget(definition.legacyStrength),
  };
}

